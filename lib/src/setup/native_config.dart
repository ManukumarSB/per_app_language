/// Pure string transforms behind `dart run per_app_language:setup`.
///
/// Kept free of `dart:io` so they're easy to test; `bin/setup.dart` does the
/// file reading and writing.
library;

/// Finds the locale of an `.arb` file: the `@@locale` key if present,
/// otherwise the suffix of the file name (`app_pt_BR.arb` → `pt-BR`).
///
/// Returns a BCP 47 tag with hyphens, or null if neither gives one.
String? localeOfArb(String fileName, String contents) {
  final declared = RegExp(r'"@@locale"\s*:\s*"([^"]+)"').firstMatch(contents);
  if (declared != null) return _normalize(declared.group(1)!);

  final base = fileName.replaceAll(RegExp(r'\.arb$'), '');
  // app_en.arb, intl_pt_BR.arb, strings_zh_Hant_TW.arb
  final match = RegExp(
    r'_([a-zA-Z]{2,3}(?:_[A-Za-z]{4})?(?:_(?:[A-Za-z]{2}|\d{3}))?)$',
  ).firstMatch(base);
  return match == null ? null : _normalize(match.group(1)!);
}

String _normalize(String tag) {
  final parts = tag.replaceAll('_', '-').split('-');
  return [
    parts.first.toLowerCase(),
    for (final p in parts.skip(1))
      p.length == 4
          ? p[0].toUpperCase() + p.substring(1).toLowerCase()
          : p.toUpperCase(),
  ].join('-');
}

/// Contents of `android/app/src/main/res/xml/locales_config.xml`.
String localesConfigXml(List<String> locales) {
  final entries = locales
      .map((l) => '    <locale android:name="$l"/>')
      .join('\n');
  return '''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by per_app_language. Lists the languages shown in
     Settings > Apps > (this app) > Language on Android 13+. -->
<locale-config xmlns:android="http://schemas.android.com/apk/res/android">
$entries
</locale-config>
''';
}

/// Adds `android:localeConfig="@xml/locales_config"` to the `<application>`
/// tag of an AndroidManifest.xml, if it isn't there.
///
/// Throws a [FormatException] if there's no `<application>` tag.
String patchAndroidManifest(String manifest) {
  if (manifest.contains('android:localeConfig')) return manifest;

  final tag = RegExp(r'<application\b').firstMatch(manifest);
  if (tag == null) {
    throw const FormatException('No <application> tag in AndroidManifest.xml');
  }

  // Match the indentation of the attribute on the next line, so the diff
  // looks like someone typed it.
  final rest = manifest.substring(tag.end);
  final indent =
      RegExp(r'^\s*\n([ \t]+)android:').firstMatch(rest)?.group(1) ??
      '        ';
  const attribute = 'android:localeConfig="@xml/locales_config"';
  final onOwnLine = rest.startsWith(RegExp(r'\s*\n'));
  final insert = onOwnLine ? '\n$indent$attribute' : ' $attribute';
  return manifest.substring(0, tag.end) + insert + rest;
}

/// Sets `CFBundleLocalizations` in an Info.plist to [locales], replacing any
/// existing list. iOS only shows the per-app Language row in Settings when
/// the app declares more than one localization.
///
/// Throws a [FormatException] if the plist has no top-level `<dict>`.
String patchInfoPlist(String plist, List<String> locales) {
  // Info.plist uses underscores for regions (pt_BR).
  final items = locales
      .map((l) => '\t\t<string>${l.replaceAll('-', '_')}</string>')
      .join('\n');
  final block =
      '\t<key>CFBundleLocalizations</key>\n\t<array>\n$items\n\t</array>\n';

  final existing = RegExp(
    r'[ \t]*<key>CFBundleLocalizations</key>\s*<array>.*?</array>[ \t]*\n?',
    dotAll: true,
  ).firstMatch(plist);
  if (existing != null) {
    return plist.replaceRange(existing.start, existing.end, block);
  }

  final end = plist.lastIndexOf('</dict>');
  if (end == -1) throw const FormatException('No <dict> in Info.plist');
  return plist.substring(0, end) + block + plist.substring(end);
}
